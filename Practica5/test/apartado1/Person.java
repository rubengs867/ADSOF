package apartado1;

public class Person {
  private String name;
  private int age;
  private int weight;
  private int height;
  private boolean male;

  public Person(String name, int age, int weight, int height, boolean male) {
    this.name = name;
    this.age = age;
    this.weight = weight;
    this.height = height;
    this.male = male;
  }
}
